/** An unknown key (e.g. hand-edited data) draws the list's fallback instead of nothing. */
export function ListIcon({ name, kind, className }: { name: string; kind: ListKind; className?: string }) {
  const Icon = LIST_ICONS[name] ?? LIST_ICONS[FALLBACK_ICON[kind]];
  return <Icon className={className} aria-hidden="true" />;
}
